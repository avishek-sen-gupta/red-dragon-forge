CODEQL_COBOL = Path(__file__).resolve().parents[4] / "codeql-cobol"


class Colour(Enum):
    RED = "R"


@dataclass(frozen=True)
class Leaf:
    name: str
    size: int
    flag: bool
    colour: Colour


@dataclass(frozen=True)
class Other:
    text: str


@dataclass(frozen=True)
class Tree:
    """One field of each shape the generator maps."""

    leaf: Leaf
    either: Leaf | Other
    maybe: Leaf | None
    leaves: list[Leaf]
    tags: tuple[str, ...]
    pairs: list[tuple[Colour, list[str]]]
    options: dict[str, Other | None]
    span: SourceSpan | None


NAMING = Naming(
    location=SourceSpan,
    modules=(),
    unions={frozenset({Leaf, Other}): "Part"},
    extended={},
)

LEAF = Leaf("a", 2, True, Colour.RED)
TREE = Tree(
    LEAF,
    Other("o"),
    None,
    [LEAF],
    ("x", "y"),
    [(Colour.RED, ["p"])],
    {"K": Other("v"), "N": None},
    SourceSpan(line_start=1, col_start=2, line_end=3, col_end=4),
)

