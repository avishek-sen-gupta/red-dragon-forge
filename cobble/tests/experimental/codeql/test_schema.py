def test_each_field_shape_becomes_its_tables_and_getters() -> None:
    schema = schema_of((Tree,), NAMING)
    assert dbscheme_text(schema, "PREAMBLE\n") == HEADER + "\nPREAMBLE\n\n" + TABLES
    assert ql_text(schema) == CLASSES


def test_a_value_writes_a_row_per_field_and_element() -> None:
    """An absent field and a map entry holding nothing write no row; labels are
    positions under the parent's."""
    writer = AstWriter(schema_of((Tree,), NAMING), Label("file"))
    assert trap_text(writer.rows(TREE, "cobol_tree", Label("t"))) == ROWS


def test_the_committed_schema_and_classes_are_what_the_generator_writes() -> None:
    """Regenerate with cobble-experimental-codeql-schema when the parser's types
    change."""
    dbscheme, ql = generated()
    committed = CODEQL_COBOL / "extractors" / "cobol" / "cobol.dbscheme"
    classes = (
        CODEQL_COBOL / "ql" / "lib" / "cobol" / "ast" / "internal" / "Generated.qll"
    )
    assert committed.read_text(encoding="utf-8") == dbscheme
    assert classes.read_text(encoding="utf-8") == ql
